CREATE TABLE IF NOT EXISTS CANCELLATION_REQUESTS
(
    CANCELLATION_REQUEST_ID INT GENERATED BY DEFAULT AS IDENTITY,
    BOOKING_ID INT NOT NULL,
    REQUESTED_BY INT NOT NULL,
    REQUEST_STATUS VARCHAR(10) DEFAULT 'REQUESTED' NOT NULL,
    REFUND_PERCENT NUMERIC(5,2) NOT NULL,
    REFUND_AMOUNT NUMERIC(10,2) DEFAULT 0 NOT NULL,
    REQUESTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DECIDED_BY INT,
    DECIDED_AT TIMESTAMP,

    CONSTRAINT PK_CANCELLATION_REQUESTS PRIMARY KEY (CANCELLATION_REQUEST_ID),
    CONSTRAINT FK_CANCELLATION_REQUEST_BOOKING
        FOREIGN KEY (BOOKING_ID) REFERENCES BOOKINGS(BOOKING_ID),
    CONSTRAINT FK_CANCELLATION_REQUEST_USER
        FOREIGN KEY (REQUESTED_BY) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_CANCELLATION_DECISION_USER
        FOREIGN KEY (DECIDED_BY) REFERENCES USERS(USER_ID),
    CONSTRAINT CK_CANCELLATION_REQUEST_STATUS
        CHECK (REQUEST_STATUS IN ('REQUESTED','APPROVED','REJECTED')),
    CONSTRAINT CK_CANCELLATION_REFUND_PERCENT
        CHECK (REFUND_PERCENT BETWEEN 0 AND 100),
    CONSTRAINT CK_CANCELLATION_REFUND_AMOUNT
        CHECK (REFUND_AMOUNT >= 0)
);

CREATE INDEX IF NOT EXISTS IDX_CANCELLATION_REQUEST_STATUS
    ON CANCELLATION_REQUESTS (REQUEST_STATUS, REQUESTED_AT);
