-- 12 seats per local seed coach.
INSERT INTO SEATS (COACH_ID, SEAT_NUMBER, SEAT_TYPE)
SELECT C.COACH_ID, CAST(LVL AS VARCHAR),
       CASE
         WHEN CT.CLASS_CODE = 'AC_B' THEN 'BERTH'
         WHEN (LVL % 4) IN (1,0) THEN 'WINDOW'
         ELSE 'AISLE'
       END
FROM COACHES C
JOIN CLASS_TYPES CT ON CT.CLASS_ID = C.CLASS_ID
CROSS JOIN generate_series(1, 12) AS LVL
WHERE C.TRAIN_ID = (SELECT TRAIN_ID FROM TRAINS WHERE TRAIN_CODE='SUBORNO');

INSERT INTO FARE_RULES (TRAIN_ID, CLASS_ID, RATE_PER_KM, BASE_FARE)
SELECT T.TRAIN_ID, C.CLASS_ID,
       CASE C.CLASS_CODE WHEN 'S_CHAIR' THEN 1.666667 WHEN 'SN' THEN 3.666667 ELSE 6.000000 END,
       0
FROM TRAINS T
CROSS JOIN CLASS_TYPES C
WHERE T.TRAIN_CODE='SUBORNO'
  AND C.CLASS_CODE IN ('S_CHAIR','SN','AC_B');

-- -------------------- TODAY'S SEEDED TRIPS --------------------
-- UP starts five minutes after this seed is run.
INSERT INTO TRIPS
    (TRAIN_ID, ROUTE_ID, JOURNEY_DATE, SCHEDULED_DEPARTURE, SCHEDULED_ARRIVAL,
     TRIP_STATUS, OPERATOR_USER_ID)
SELECT T.TRAIN_ID,
       R.ROUTE_ID,
       CURRENT_DATE,
       CURRENT_TIMESTAMP + INTERVAL '5 MINUTE',
       CURRENT_TIMESTAMP + INTERVAL '305 MINUTE',
       'SCHEDULED',
       U.USER_ID
FROM TRAINS T, ROUTES R, USERS U
WHERE T.TRAIN_CODE='SUBORNO'
  AND R.TRAIN_ID=T.TRAIN_ID
  AND R.ROUTE_CODE='SUB-UP'
  AND U.EMAIL='operator@ferrovia.local';

