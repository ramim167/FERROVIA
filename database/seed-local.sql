-- Materialize route-stop timetable into each actual trip.
INSERT INTO TRIP_STOPS
    (TRIP_ID, ROUTE_STOP_ID, STATION_ID, STOP_SEQUENCE,
     SCHEDULED_ARRIVAL, SCHEDULED_DEPARTURE)
SELECT T.TRIP_ID,
       RS.ROUTE_STOP_ID,
       RS.STATION_ID,
       RS.STOP_SEQUENCE,
       CASE WHEN RS.ARRIVAL_OFFSET_MIN IS NULL THEN NULL
            ELSE T.SCHEDULED_DEPARTURE + (RS.ARRIVAL_OFFSET_MIN * INTERVAL '1 MINUTE') END,
       CASE WHEN RS.DEPARTURE_OFFSET_MIN IS NULL THEN NULL
            ELSE T.SCHEDULED_DEPARTURE + (RS.DEPARTURE_OFFSET_MIN * INTERVAL '1 MINUTE') END
FROM TRIPS T
JOIN ROUTE_STOPS RS ON RS.ROUTE_ID = T.ROUTE_ID
WHERE T.TRAIN_ID = (SELECT TRAIN_ID FROM TRAINS WHERE TRAIN_CODE='SUBORNO');

-- Initial physical assignment only for the UP trip.
INSERT INTO TRAINSET_ASSIGNMENTS
    (TRIP_ID, TRAINSET_ID, TRAIN_ID, ASSIGNMENT_TYPE, ASSIGNMENT_STATUS, REASON)
SELECT T.TRIP_ID, TS.TRAINSET_ID, T.TRAIN_ID, 'NORMAL', 'RESERVED', 'Initial seed assignment'
FROM TRIPS T
JOIN ROUTES R ON R.ROUTE_ID=T.ROUTE_ID
JOIN TRAINSETS TS ON TS.TRAIN_ID=T.TRAIN_ID AND TS.TRAINSET_CODE='SUB-01'
WHERE R.ROUTE_CODE='SUB-UP';

-- Generate trip-seat inventory for both trips.
INSERT INTO TRIP_SEATS (TRIP_ID, SEAT_ID, SEAT_STATUS)
SELECT T.TRIP_ID, S.SEAT_ID, 'AVAILABLE'
FROM TRIPS T
JOIN COACHES C ON C.TRAIN_ID=T.TRAIN_ID
JOIN SEATS S ON S.COACH_ID=C.COACH_ID
WHERE T.TRAIN_ID=(SELECT TRAIN_ID FROM TRAINS WHERE TRAIN_CODE='SUBORNO');
